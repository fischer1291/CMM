#!/usr/bin/env node
/**
 * The website shows only six pages of the app (datenschutz, impressum,
 * nutzungsbedingungen, melden, einladung, kreis) and the landing page at /.
 * Every other screen in app/
 * needs a <route>.web.tsx sibling that re-exports components/AppOnlyWeb.tsx,
 * otherwise expo export renders it as a public page. CI runs this; the
 * matching test is tests/webStubs.test.ts. The stub's noindex meta tag only
 * exists after hydration (the exported HTML is a shell), so build-web.sh also
 * writes a Netlify _headers file with X-Robots-Tag: noindex for every stub
 * route, which crawlers without JavaScript see as well.
 *
 *   node scripts/check-web-stubs.js             check (CI)
 *   node scripts/check-web-stubs.js --headers   print the _headers file
 */
/* global __dirname */
const fs = require('fs');
const path = require('path');

const APP_DIR = path.join(__dirname, '..', 'app');
// Routes without a stub: public on the web, or replaced by the landing page
const PUBLIC_ROUTES = ['datenschutz', 'impressum', 'nutzungsbedingungen', 'melden', 'einladung', 'kreis', '(tabs)/index'];

/** Route files below `dir` (recursive, relative, POSIX), without layouts and platform files. */
function listRoutes(dir, prefix = '') {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      out.push(...listRoutes(path.join(dir, entry.name), rel));
      continue;
    }
    const m = entry.name.match(/^(.+?)(\.(web|ios|android|native))?\.tsx?$/);
    if (!m || m[2]) continue; // not a route, or already a platform file
    const name = m[1];
    if (name.startsWith('_') || name.startsWith('+')) continue; // _layout, +html, +not-found
    out.push({ route: prefix ? `${prefix}/${name}` : name, file: rel });
  }
  return out;
}

/** Which routes lack their web stub? Pure, for the tests. */
function missingStubs(routes, files, publicRoutes = PUBLIC_ROUTES) {
  const set = new Set(files);
  return routes.filter((r) => !publicRoutes.includes(r.route) && !set.has(`${r.route}.web.tsx`)).map((r) => r.route);
}

/** Stubs whose route no longer exists. */
function orphanStubs(routes, files) {
  const known = new Set(routes.map((r) => r.route));
  return files.filter((f) => f.endsWith('.web.tsx')).map((f) => f.replace(/\.web\.tsx$/, '')).filter((r) => !known.has(r));
}

/** URL of a route on the web: route groups like (tabs) are not part of it. */
function webPath(route) {
  const clean = route.split('/').filter((seg) => !/^\(.*\)$/.test(seg)).join('/');
  return `/${clean === 'index' ? '' : clean}`;
}

/**
 * Netlify _headers: noindex for every stub route, the raw group path included.
 * A public route inside a group ((tabs)/index: its clean URL / is the landing
 * page) still gets its raw paths /(tabs) and /(tabs)/index marked, because
 * expo export writes dist/(tabs)/index.html, the app's home shell. Pure.
 */
function robotsHeaders(routes, publicRoutes = PUBLIC_ROUTES) {
  const paths = new Set();
  for (const r of routes) {
    if (!publicRoutes.includes(r.route)) paths.add(webPath(r.route));
    if (r.route.includes('(')) {
      paths.add(`/${r.route}`);
      if (r.route.endsWith('/index')) paths.add(`/${r.route.replace(/\/index$/, '')}`);
    }
  }
  return [...paths].sort().map((p) => `${p}\n  X-Robots-Tag: noindex`).join('\n') + '\n';
}

function allFiles(dir, prefix = '') {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) out.push(...allFiles(path.join(dir, entry.name), rel));
    else out.push(rel);
  }
  return out;
}

function main() {
  const routes = listRoutes(APP_DIR);
  if (process.argv.includes('--headers')) {
    process.stdout.write(`# App-only routes, generated by scripts/check-web-stubs.js --headers\n${robotsHeaders(routes)}`);
    return;
  }
  const files = allFiles(APP_DIR);
  const missing = missingStubs(routes, files);
  const orphans = orphanStubs(routes, files);
  if (missing.length) {
    console.error('✖ Diese Screens landen ohne Stub im Web-Export. Anlegen als app/<route>.web.tsx mit:');
    console.error("  export { default } from '../components/AppOnlyWeb';");
    for (const r of missing) console.error(`  - ${r}`);
  }
  if (orphans.length) {
    console.error('✖ Web-Stubs ohne Screen (löschen):');
    for (const r of orphans) console.error(`  - app/${r}.web.tsx`);
  }
  if (missing.length || orphans.length) process.exit(1);
  const stubs = files.filter((f) => f.endsWith('.web.tsx')).length;
  console.log(`✔ Web-Routen: ${PUBLIC_ROUTES.length} öffentlich, ${stubs} Screens nur in der App`);
}

module.exports = { listRoutes, missingStubs, orphanStubs, webPath, robotsHeaders, PUBLIC_ROUTES };
if (require.main === module) main();
